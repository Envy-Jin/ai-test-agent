"""
Day 30 练习 3：pytest 代码渲染器 —— ApiDoc/计划 → conftest.py + test_api_suite.py（确定性模板）

设计（步骤 1 决策 B/C 落地）：
  - 模型只出接口语义（ApiDoc），pytest 代码由这里确定性渲染：
    语法稳定、风格统一、同输入同输出（可 diff 可评审）
  - 行列表拼接（不用 f-string 大模板）：pytest 代码里全是 {}（dict/函数体/f-string），
    再套一层 f-string 就是花括号地狱 → 渲染层全部用字符串拼接，生成代码里的 {} 原样保留
  - 每端点一个 Test 类，三件套必出（正常/参数缺失/越权或错误凭据）——学习计划硬性要求
  - parametrize 的 argvalues 必须是 list 字面量（pytest 9.1.0 起生成器/迭代器已弃用，
    2026-06-13 联网确认：可迭代对象会被耗尽导致用例静默丢失）
  - ast.parse 校验：语法可编译才落盘（正确性第一层；行为正确性靠练习 4 真实执行）

用法：
  python -c "from day30_pytest_generator import exp3_render_smoke; exp3_render_smoke()"  # 零 API
"""
